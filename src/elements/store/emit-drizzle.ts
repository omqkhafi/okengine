/**
 * Map a store.sql driver id to an emit dialect.
 *
 * @param driverId - Protocol driver id (`postgres` · `pglite` · …)
 */
export function dialectFromDriverId(driverId: string | undefined): SqlDialect {
  if (driverId === undefined || driverId === "postgres" || driverId === "pglite") {
    return "postgres";
  }
  throw new Error(
    `oke schema emit: store.sql driver "${driverId}" is not supported (postgres | pglite)`,
  );
}

/**
 * Serialize one column to a Drizzle builder chain.
 *
 * Emits drizzle-exact calls for every {@link FieldSqlType}, carrying options
 * (`length`, `precision`, `scale`, `withTimezone`, `mode`, `fields`,
 * `enumValues`). Temporal modes are always pinned explicitly — rc.5 library
 * defaults differ from OKE's (bare `date()` = string, bare `timestamp()` =
 * Date).
 *
 * Postgres INTEGER is 32-bit; abstract `integer` (often ms clocks) → bigint.
 * drizzle-orm's `bigint()` requires `{ mode }` — omitting it throws on
 * `config.mode` when the generated schema is loaded by drizzle-kit push.
 *
 * @param col - Column decl
 * @param dialect - Target dialect (affects import names only at file level)
 */
export function emitColumnSource(col: SchemaColumnDecl, _dialect: SqlDialect = "postgres"): string {
  let expr = `${columnFactoryCall(col)}`;
  if (col.primaryKey) expr += ".primaryKey()";
  else if (col.notNull) expr += ".notNull()";
  if (col.unique) expr += ".unique()";
  if (col.defaultValue !== undefined) {
    expr += `.default(${literalSource(col.defaultValue)})`;
  }
  if (col.defaultFnKind === "id") expr += ".$defaultFn(id)";
  else if (col.defaultFnKind === "now") expr += ".$defaultFn(now)";
  else if (col.defaultFnKind === "nowIso") expr += ".$defaultFn(nowIso)";
  else if (col.defaultFnKind === "nowDate") expr += ".$defaultFn(nowDate)";
  if (col.references) {
    const target = col.references.ref();
    const targetTable = exportNameForTable(target.tableName ?? "unknown");
    const targetCol = target.key;
    expr += `.references(() => ${targetTable}.${targetCol}`;
    const actions = col.references.actions;
    if (actions && (actions.onDelete || actions.onUpdate)) {
      const parts: string[] = [];
      if (actions.onDelete) parts.push(`onDelete: ${JSON.stringify(actions.onDelete)}`);
      if (actions.onUpdate) parts.push(`onUpdate: ${JSON.stringify(actions.onUpdate)}`);
      expr += `, { ${parts.join(", ")} }`;
    }
    expr += ")";
  }
  return expr;
}

/** Factory call for a column type with its options, e.g. `varchar("x", { length: 256 })`. */
function columnFactoryCall(col: SchemaColumnDecl): string {
  const name = JSON.stringify(col.sqlName);
  const o = col.typeOptions ?? {};
  switch (col.sqlType) {
    case "text":
      return enumConfig(o) !== undefined
        ? `text(${name}, { enum: ${JSON.stringify(o.enumValues)} })`
        : `text(${name})`;
    case "varchar":
    case "char": {
      const factory = col.sqlType;
      const configParts: string[] = [];
      if (o.length !== undefined) configParts.push(`length: ${o.length}`);
      const enumValues = enumConfig(o);
      if (enumValues !== undefined) configParts.push(`enum: ${enumValues}`);
      return configParts.length > 0
        ? `${factory}(${name}, { ${configParts.join(", ")} })`
        : `${factory}(${name})`;
    }
    case "boolean":
      return `boolean(${name})`;
    case "smallint":
      return `smallint(${name})`;
    case "integer":
      // Postgres INTEGER is 32-bit — abstract integer (ms clocks) widens.
      return `bigint(${name}, { mode: "number" })`;
    case "bigint":
      return `bigint(${name}, { mode: ${JSON.stringify(o.mode ?? "number")} })`;
    case "serial":
      return `serial(${name})`;
    case "smallserial":
      return `smallserial(${name})`;
    case "bigserial":
      return `bigserial(${name}, { mode: ${JSON.stringify(o.mode ?? "number")} })`;
    case "numeric": {
      const configParts: string[] = [];
      if (o.precision !== undefined) configParts.push(`precision: ${o.precision}`);
      if (o.scale !== undefined) configParts.push(`scale: ${o.scale}`);
      if (o.mode !== undefined && o.mode !== "string") {
        configParts.push(`mode: ${JSON.stringify(o.mode)}`);
      }
      // rc.5 factory shape: numeric(name, config?) where the config is a
      // discriminated union requiring at least one of precision/scale/mode.
      return configParts.length > 0
        ? `numeric(${name}, { ${configParts.join(", ")} })`
        : `numeric(${name})`;
    }
    case "real":
      return `real(${name})`;
    case "doublePrecision":
      return `doublePrecision(${name})`;
    case "json":
      return `json(${name})`;
    case "jsonb":
      return `jsonb(${name})`;
    case "uuid":
      return `uuid(${name})`;
    case "time": {
      const configParts: string[] = [];
      if (o.withTimezone !== undefined) configParts.push(`withTimezone: ${o.withTimezone}`);
      if (o.precision !== undefined) configParts.push(`precision: ${o.precision}`);
      return configParts.length > 0
        ? `time(${name}, { ${configParts.join(", ")} })`
        : `time(${name})`;
    }
    case "timestamp": {
      const configParts: string[] = [`mode: ${JSON.stringify(o.mode ?? "date")}`];
      if (o.precision !== undefined) configParts.push(`precision: ${o.precision}`);
      if (o.withTimezone !== undefined) configParts.push(`withTimezone: ${o.withTimezone}`);
      return `timestamp(${name}, { ${configParts.join(", ")} })`;
    }
    case "date":
      return `date(${name}, { mode: ${JSON.stringify(o.mode ?? "date")} })`;
    case "interval": {
      const configParts: string[] = [];
      if (o.fields !== undefined) configParts.push(`fields: ${JSON.stringify(o.fields)}`);
      if (o.precision !== undefined) configParts.push(`precision: ${o.precision}`);
      return configParts.length > 0
        ? `interval(${name}, { ${configParts.join(", ")} })`
        : `interval(${name})`;
    }
    case "point":
      return o.mode !== undefined && o.mode !== "tuple"
        ? `point(${name}, { mode: ${JSON.stringify(o.mode)} })`
        : `point(${name})`;
    case "line":
      return o.mode !== undefined && o.mode !== "tuple"
        ? `line(${name}, { mode: ${JSON.stringify(o.mode)} })`
        : `line(${name})`;
    case "bytea":
      return `bytea(${name})`;
    case "inet":
      return `inet(${name})`;
    case "cidr":
      return `cidr(${name})`;
    case "macaddr":
      return `macaddr(${name})`;
    case "macaddr8":
      return `macaddr8(${name})`;
  }
}

function enumConfig(o: FieldTypeOptions): string | undefined {
  if (!o.enumValues || o.enumValues.length === 0) return undefined;
  return JSON.stringify(o.enumValues);
}

function literalSource(value: string | number | boolean | Date | Buffer | null): string {
  if (value === null) return "null";
  if (value instanceof Date) return `new Date(${JSON.stringify(value.toISOString())})`;
  if (Buffer.isBuffer(value))
    return `Buffer.from(${JSON.stringify(value.toString("base64"))}, "base64")`;
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  return String(value);
}

function emitColRef(ref: RelationColumnRef): string {
  return `r.${ref.table}.${ref.column}`;
}

function emitColRefs(
  value: RelationColumnRef | readonly RelationColumnRef[] | undefined,
): string | undefined {
  if (value === undefined) return undefined;
  if (Array.isArray(value)) {
    const refs = value as readonly RelationColumnRef[];
    if (refs.length === 1) return emitColRef(refs[0]!);
    return `[${refs.map(emitColRef).join(", ")}]`;
  }
  return emitColRef(value as RelationColumnRef);
}

function emitRelationEntry(entry: SchemaRelationEntry): string {
  const helper = entry.kind === "one" ? "one" : "many";
  const parts: string[] = [];
  const from = emitColRefs(entry.from);
  const to = emitColRefs(entry.to);
  if (from !== undefined) parts.push(`from: ${from}`);
  if (to !== undefined) parts.push(`to: ${to}`);
  if (entry.kind === "one" && entry.optional !== undefined) {
    parts.push(`optional: ${entry.optional ? "true" : "false"}`);
  }
  if (entry.alias !== undefined) parts.push(`alias: ${JSON.stringify(entry.alias)}`);
  const config = parts.length > 0 ? `{ ${parts.join(", ")} }` : "";
  return `r.${helper}.${entry.target}(${config})`;
}

/**
 * Emit a `defineRelations(...)` block from abstract relations decls.
 *
 * @param relations - Relations declarations (typically one)
 */
export function emitRelationsSource(relations: readonly SchemaRelationsDecl[]): string {
  if (relations.length === 0) return "";
  const blocks: string[] = [];
  for (const rel of relations) {
    const schemaKeys = rel.tableKeys.join(", ");
    const tableBlocks: string[] = [];
    for (const [tableKey, tableRels] of Object.entries(rel.config)) {
      const relLines = Object.entries(tableRels).map(
        ([relName, entry]) => `    ${relName}: ${emitRelationEntry(entry)},`,
      );
      tableBlocks.push(`  ${tableKey}: {\n${relLines.join("\n")}\n  },`);
    }
    blocks.push(
      `export const relations = defineRelations({ ${schemaKeys} }, (r) => ({\n${tableBlocks.join("\n")}\n}));`,
    );
  }
  return blocks.join("\n\n");
}

/** Options for {@link emitDrizzleSource}. */
export interface EmitDrizzleSourceOptions {
  readonly relations?: readonly SchemaRelationsDecl[];
}

function tableExportName(table: SchemaTableDecl): string {
  return exportNameForTable(schemaTableSqlName(table) ?? table.name);
}

function referencedExportNames(table: SchemaTableDecl): string[] {
  const self = tableExportName(table);
  const names = new Set<string>();
  for (const col of Object.values(table.columns)) {
    if (!col.references) continue;
    const target = col.references.ref();
    const targetName = exportNameForTable(target.tableName ?? "unknown");
    if (targetName !== self) names.add(targetName);
  }
  return [...names].sort();
}

function emitImportLines(
  tables: readonly SchemaTableDecl[],
  options: { readonly relations?: boolean } = {},
): string[] {
  const usedFactories = new Set<string>();
  for (const table of tables) {
    for (const col of Object.values(table.columns)) {
      // Abstract `integer` emits as drizzle `bigint` (32-bit widening).
      usedFactories.add(col.sqlType === "integer" ? "bigint" : col.sqlType);
    }
  }
  const pgIntImport = [...usedFactories].filter(
    (name) => name !== "pgTable" && name !== "pgPolicy",
  );
  const needsPolicy = tables.some((t) => (t.policies?.length ?? 0) > 0);
  const coreNames = ["pgTable", ...pgIntImport, needsPolicy ? "pgPolicy" : null].filter(
    (name): name is string => name !== null,
  );
  const lines = [`import { ${coreNames.join(", ")} } from "drizzle-orm/pg-core";`];
  if (needsPolicy) lines.push(`import { sql } from "drizzle-orm";`);
  if (options.relations) lines.push(`import { defineRelations } from "drizzle-orm";`);

  const needsId = tables.some((t) =>
    Object.values(t.columns).some((c) => c.defaultFnKind === "id"),
  );
  const needsNow = tables.some((t) =>
    Object.values(t.columns).some((c) => c.defaultFnKind === "now"),
  );
  const needsNowIso = tables.some((t) =>
    Object.values(t.columns).some((c) => c.defaultFnKind === "nowIso"),
  );
  const needsNowDate = tables.some((t) =>
    Object.values(t.columns).some((c) => c.defaultFnKind === "nowDate"),
  );
  const helperNames = [
    needsId ? "id" : null,
    needsNow ? "now" : null,
    needsNowIso ? "nowIso" : null,
    needsNowDate ? "nowDate" : null,
  ].filter((x): x is string => x !== null);
  if (helperNames.length > 0) {
    lines.push(`import { ${helperNames.join(", ")} } from "okengine/store";`);
  }
  return lines;
}

function joinGeneratedModule(parts: readonly string[]): string {
  return parts.filter((line, i, arr) => !(line === "" && arr[i - 1] === "")).join("\n");
}

/**
 * Emit a full Drizzle schema module from abstract table decls.
 *
 * @param tables - App + plugin tables (already merged)
 * @param dialect - Always `postgres` (`pgTable`); retained for call-site clarity
 * @param options - Optional relations to emit as `defineRelations`
 */
export function emitDrizzleSource(
  tables: readonly SchemaTableDecl[],
  dialect: SqlDialect = "postgres",
  options: EmitDrizzleSourceOptions = {},
): string {
  const relations = options.relations ?? [];
  const blocks = tables.map((table) => emitTableBlock(table, dialect));
  const relationsBlock = emitRelationsSource(relations);
  return joinGeneratedModule([
    GENERATED_SCHEMA_HEADER,
    ...emitImportLines(tables, { relations: relations.length > 0 }),
    "",
    blocks.join("\n\n"),
    relationsBlock ? `\n${relationsBlock}` : "",
    "",
  ]);
}

/**
 * One generated table module (`drizzle/<export>.ts`).
 *
 * @param table - Table declaration
 * @param dialect - Always `postgres`
 */
export function emitDrizzleTableSource(
  table: SchemaTableDecl,
  dialect: SqlDialect = "postgres",
): string {
  const refs = referencedExportNames(table).map(
    (name) => `import { ${name} } from ${JSON.stringify(`./${name}.ts`)};`,
  );
  return joinGeneratedModule([
    GENERATED_SCHEMA_HEADER,
    ...emitImportLines([table]),
    ...refs,
    "",
    emitTableBlock(table, dialect),
    "",
  ]);
}

/**
 * Generated `drizzle/relations.ts` when declare relations exist.
 *
 * @param relations - Relations declarations
 */
export function emitDrizzleRelationsFileSource(relations: readonly SchemaRelationsDecl[]): string {
  if (relations.length === 0) return "";
  const keys = new Set<string>();
  for (const rel of relations) {
    for (const k of rel.tableKeys) keys.add(k);
  }
  const imports = [...keys]
    .sort()
    .map((name) => `import { ${name} } from ${JSON.stringify(`./${name}.ts`)};`);
  return joinGeneratedModule([
    GENERATED_SCHEMA_HEADER,
    `import { defineRelations } from "drizzle-orm";`,
    ...imports,
    "",
    emitRelationsSource(relations),
    "",
  ]);
}

/**
 * Generated `drizzle/index.ts` barrel.
 *
 * @param fileNames - Table (and relations) filenames to re-export
 */
export function emitDrizzleIndexSource(fileNames: readonly string[]): string {
  const exports = fileNames.map((name) => `export * from ${JSON.stringify(`./${name}`)};`);
  return `${GENERATED_SCHEMA_HEADER}\n${exports.join("\n")}\n`;
}

/**
 * Filename → source for a generated `drizzle/` folder (one table per file).
 *
 * @param tables - App + plugin tables (already merged)
 * @param dialect - Always `postgres`
 * @param options - Optional relations file
 */
export function emitDrizzleFolderSources(
  tables: readonly SchemaTableDecl[],
  dialect: SqlDialect = "postgres",
  options: EmitDrizzleSourceOptions = {},
): ReadonlyMap<string, string> {
  const files = new Map<string, string>();
  const tableFiles: string[] = [];
  for (const table of tables) {
    const name = `${tableExportName(table)}.ts`;
    files.set(name, emitDrizzleTableSource(table, dialect));
    tableFiles.push(name);
  }
  const relations = options.relations ?? [];
  const extra: string[] = [];
  if (relations.length > 0) {
    files.set("relations.ts", emitDrizzleRelationsFileSource(relations));
    extra.push("relations.ts");
  }
  files.set("index.ts", emitDrizzleIndexSource([...tableFiles, ...extra]));
  return files;
}

/**
 * Whether `db.generated` is the folder barrel (`drizzle/index.ts`).
 *
 * @param rel - Path relative to project root
 */
export function isFolderGeneratedRel(rel: string): boolean {
  const n = rel.replace(/\\/g, "/").replace(/\/$/, "");
  return /(?:^|\/)drizzle\/index\.tsx?$/.test(n) || /(?:^|\/)drizzle$/.test(n);
}

/**
 * Normalize `db.generated` so a directory `drizzle` becomes `drizzle/index.ts`.
 *
 * @param rel - Path relative to project root
 */
export function normalizeGeneratedRel(rel: string): string {
  const n = rel.replace(/\\/g, "/").replace(/\/$/, "");
  if (n.endsWith("/drizzle") || n === "drizzle") return `${n}/index.ts`;
  return n;
}

function emitTableBlock(table: SchemaTableDecl, dialect: SqlDialect): string {
  const lines = Object.values(table.columns).map(
    (col) => `  ${col.key}: ${emitColumnSource(col, dialect)},`,
  );
  const sqlName = schemaTableSqlName(table) ?? table.name;
  const exportName = exportNameForTable(sqlName);
  const cols = `{\n${lines.join("\n")}\n}`;
  const policies = table.policies ?? [];
  const ctor = table.rls === true ? "pgTable.withRLS" : "pgTable";
  if (policies.length === 0) {
    return `export const ${exportName} = ${ctor}(${JSON.stringify(sqlName)}, ${cols});`;
  }
  const extras = policies.map((policy) => `  ${emitPolicyExtra(policy, sqlName)},`).join("\n");
  return `export const ${exportName} = ${ctor}(${JSON.stringify(sqlName)}, ${cols}, (_t) => [\n${extras}\n]);`;
}

function emitPolicyExtra(policy: SchemaPolicyDecl, table: string): string {
  const roles = Array.isArray(policy.to)
    ? policy.to.join(", ")
    : typeof policy.to === "string"
      ? policy.to
      : "public";
  const spec = parseSqlPolicySpec({
    name: policy.name,
    table,
    as: policy.as,
    to: roles,
    for: policy.for,
    using: policy.using,
    withCheck: policy.withCheck,
  });
  return emitPgPolicySource(spec).replaceAll("\n", "\n  ");
}

function exportNameForTable(name: string): string {
  // Keep simple SQL names as-is; camelCase odd names.
  if (/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(name)) return name;
  return name.replace(/[^a-zA-Z0-9_]+/g, "_");
}

/**
 * Build a {@link SchemaTableDecl} from a plugin column map (builders or decls).
 *
 * @param name - Table name
 * @param columns - Column map
 */
export function schemaTableFromPluginColumns(
  name: string,
  columns: Readonly<Record<string, SchemaColumnInput>>,
): SchemaTableDecl {
  return schemaTable(name, columns);
}

/**
 * Whether a record looks like an abstract column map (not `{ plane }` metadata).
 *
 * @param value - Unknown second arg to plugin.table
 */
export function isAbstractColumnMap(
  value: unknown,
): value is Readonly<Record<string, SchemaColumnInput>> {
  if (!value || typeof value !== "object" || Array.isArray(value)) return false;
  const entries = Object.entries(value);
  if (entries.length === 0) return true;
  // Legacy `{ plane: "operator" }` — not columns.
  if (entries.length === 1 && entries[0]![0] === "plane" && typeof entries[0]![1] === "string") {
    return false;
  }
  return entries.every(([, v]) => isFieldBuilder(v) || isSchemaColumnDecl(v));
}

/**
 * Extract schema tables from plugin contributions that supply `field.*` columns.
 *
 * Contributions without columns (name + plane only) are skipped — auth/console
 * still use hand-written SQL for those tables.
 *
 * @param contributions - Plugin table list
 */
export function tablesFromPluginContributions(
  contributions: readonly TableContribution[],
): SchemaTableDecl[] {
  const out: SchemaTableDecl[] = [];
  for (const c of contributions) {
    const columns = c.columns;
    if (!columns || Object.keys(columns).length === 0) continue;
    if (!isAbstractColumnMap(columns)) continue;
    out.push(schemaTableFromPluginColumns(c.name, columns));
  }
  return out;
}

/**
 * Merge app + plugin abstract tables. Duplicate names throw.
 *
 * @param appTables - App declarations
 * @param pluginTables - Plugin contributions with columns
 */
export function mergeSchemaTables(
  appTables: readonly SchemaTableDecl[],
  pluginTables: readonly SchemaTableDecl[] = [],
): SchemaTableDecl[] {
  const byName = new Map<string, SchemaTableDecl>();
  for (const t of [...appTables, ...pluginTables]) {
    if (byName.has(t.name)) {
      throw new Error(
        `store schema: duplicate table "${t.name}" (plugins may add whole tables only — no column injection into app-owned tables)`,
      );
    }
    byName.set(t.name, t);
  }
  return [...byName.values()];
}

