/**
 * When abstract decls and/or plugin `field.*` tables exist, write the generated
 * Drizzle schema. Returns whether a file was written.
 *
 * @param options - Paths / dialect / plugins
 */
export async function maybeEmitDomainSchema(
  options: EmitDomainSchemaOptions,
): Promise<{ readonly emitted: boolean; readonly path?: string; readonly tableCount?: number }> {
  const cwd = options.cwd;
  const resolved = resolveEmitPaths(cwd, {
    ...(options.declarePath !== undefined ? { declare: options.declarePath } : {}),
    ...(options.outPath !== undefined ? { generated: options.outPath } : {}),
  });
  const declareAbs = resolved.declarePath;
  const outAbs = resolved.outPath;
  const declareRel = declareAbs.startsWith(`${cwd}/`)
    ? declareAbs.slice(cwd.length + 1)
    : declareAbs;
  const outRel = outAbs.startsWith(`${cwd}/`) ? outAbs.slice(cwd.length + 1) : outAbs;
  const declareFile = Bun.file(declareAbs);

  let appTables: SchemaTableDecl[] = [];
  let appRelations: SchemaRelationsDecl[] = [];
  if (await declareFile.exists()) {
    let mod: Record<string, unknown>;
    try {
      mod = (await import(declareAbs)) as Record<string, unknown>;
    } catch (err) {
      options.write?.(
        `oke db: failed to load schema declare module ${declareRel}: ${err instanceof Error ? err.message : String(err)}\n`,
      );
      throw err;
    }
    appTables = tablesFromExports(mod);
    appRelations = relationsFromExports(mod);
  }

  const fromPlugins = tablesFromPluginContributions(options.pluginTables ?? []);
  if (appTables.length === 0 && fromPlugins.length === 0) {
    return { emitted: false };
  }

  const tables = mergeSchemaTables(appTables, fromPlugins);
  if (isFolderGeneratedRel(outRel)) {
    const dirAbs = dirname(outAbs);
    const files = emitDrizzleFolderSources(tables, options.dialect, {
      relations: appRelations,
    });
    await writeGeneratedFolder(dirAbs, files);
    await removeLegacySingleDrizzleFile(dirAbs);
    options.write?.(
      `oke db: emitted ${outRel} (${tables.length} table${tables.length === 1 ? "" : "s"}, ${options.dialect})\n`,
    );
    return { emitted: true, path: outAbs, tableCount: tables.length };
  }

  const source = emitDrizzleSource(tables, options.dialect, { relations: appRelations });
  await mkdir(dirname(outAbs), { recursive: true });
  await writeFile(outAbs, source, "utf8");
  options.write?.(
    `oke db: emitted ${outRel} (${tables.length} table${tables.length === 1 ? "" : "s"}, ${options.dialect})\n`,
  );
  return { emitted: true, path: outAbs, tableCount: tables.length };
}

async function writeGeneratedFolder(
  dirAbs: string,
  files: ReadonlyMap<string, string>,
): Promise<void> {
  await mkdir(dirAbs, { recursive: true });
  for (const [name, source] of files) {
    await writeFile(join(dirAbs, name), source, "utf8");
  }
  let existing: string[] = [];
  try {
    existing = await readdir(dirAbs);
  } catch {
    return;
  }
  for (const name of existing) {
    if (!name.endsWith(".ts") && !name.endsWith(".tsx")) continue;
    if (files.has(name)) continue;
    const abs = join(dirAbs, name);
    try {
      const content = await readFile(abs, "utf8");
      if (content.startsWith(GENERATED_SCHEMA_HEADER)) await unlink(abs);
    } catch {
      // ignore prune failures
    }
  }
}

async function removeLegacySingleDrizzleFile(dirAbs: string): Promise<void> {
  if (basename(dirAbs) !== "drizzle") return;
  const sibling = join(dirname(dirAbs), basename(PREV_SINGLE_DRIZZLE_REL));
  if (!existsSync(sibling)) return;
  try {
    const content = await readFile(sibling, "utf8");
    if (content.startsWith(GENERATED_SCHEMA_HEADER)) await unlink(sibling);
  } catch {
    // ignore
  }
}

/**
 * Discover the declare module when `db.declare` is omitted.
 *
 * Order: `schema.ts` (single file) → `schema.decl.ts` (prior name) →
 * `schema/index.ts` (folder) → legacy `src/schema.decl.ts` → default
 * `schema.ts` (may not exist yet).
 *
 * @param cwd - Project root
 */
export function discoverDeclareRel(cwd: string): string {
  if (existsSync(join(cwd, DEFAULT_DECLARE_SCHEMA_REL))) {
    return DEFAULT_DECLARE_SCHEMA_REL;
  }
  if (existsSync(join(cwd, PREV_DECLARE_SCHEMA_REL))) {
    return PREV_DECLARE_SCHEMA_REL;
  }
  if (existsSync(join(cwd, DEFAULT_DECLARE_SCHEMA_DIR_REL))) {
    return DEFAULT_DECLARE_SCHEMA_DIR_REL;
  }
  if (existsSync(join(cwd, LEGACY_DECLARE_SCHEMA_REL))) {
    return LEGACY_DECLARE_SCHEMA_REL;
  }
  return DEFAULT_DECLARE_SCHEMA_REL;
}

/**
 * Discover the generated Drizzle emit path when `db.generated` is omitted.
 *
 * Order: `src/db/drizzle/index.ts`, except legacy `src/schema.generated.ts`
 * when the declare module is still on the old `src/` layout. Older single
 * files (`drizzle.ts`, `schema.drizzle.ts`) are not re-targeted — set
 * `db.generated` to keep emitting them.
 *
 * @param cwd - Project root
 * @param declareRel - Resolved declare relative path
 */
export function discoverGeneratedRel(cwd: string, declareRel: string): string {
  const preferSrcLegacy =
    declareRel === LEGACY_DECLARE_SCHEMA_REL ||
    (!existsSync(join(cwd, DEFAULT_DECLARE_SCHEMA_REL)) &&
      !existsSync(join(cwd, PREV_DECLARE_SCHEMA_REL)) &&
      !existsSync(join(cwd, DEFAULT_DECLARE_SCHEMA_DIR_REL)) &&
      existsSync(join(cwd, LEGACY_GENERATED_SCHEMA_REL)));
  if (preferSrcLegacy) return LEGACY_GENERATED_SCHEMA_REL;
  return DEFAULT_GENERATED_SCHEMA_REL;
}

/**
 * Resolve declare/out paths from an optional db config slice.
 * Prefers explicit `db.declare` / `db.generated`, then discovery.
 *
 * @param cwd - Project root
 * @param db - Config `db` block
 */
export function resolveEmitPaths(
  cwd: string,
  db?: { readonly declare?: string; readonly generated?: string },
): { readonly declarePath: string; readonly outPath: string } {
  const declareRel = db?.declare ?? discoverDeclareRel(cwd);
  const outRel = normalizeGeneratedRel(db?.generated ?? discoverGeneratedRel(cwd, declareRel));
  return {
    declarePath: join(cwd, declareRel),
    outPath: join(cwd, outRel),
  };
}

